function initDemoForm() {
  const form = document.querySelector("[data-demo-form]");
  if (!form || form.dataset.ready === "true") return;
  form.dataset.ready = "true";

  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const status = form.querySelector("[data-form-status]");
    const submit = form.querySelector('button[type="submit"]');
    const data = new FormData(form);

    if (status) status.textContent = "Enviando solicitud…";
    if (submit) submit.disabled = true;

    try {
      const response = await fetch(`${rootPath()}/api/contact`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: data.get("nombre"),
          email: data.get("email"),
          company: data.get("empresa"),
          category: data.get("categoria"),
          message: data.get("mensaje")
        })
      });

      const result = await response.json().catch(() => ({}));
      if (!response.ok || result.error) {
        throw new Error(result.error || "No se pudo enviar la solicitud");
      }

      if (status) status.textContent = uiText().form.status;
      form.reset();
    } catch (error) {
      if (status) {
        status.textContent = "No se ha podido enviar la solicitud. Inténtalo de nuevo o contacta con nosotros por email.";
      }
    } finally {
      if (submit) submit.disabled = false;
    }
  });
}

