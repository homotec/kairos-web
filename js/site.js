function scrollToHash(hash, behavior = "instant") {
  if (!hash || hash === "#") return false;
  const target = document.getElementById(decodeURIComponent(hash.slice(1)));
  if (!target) return false;

  const header = document.querySelector(".site-header");
  const headerHeight = header ? header.getBoundingClientRect().height : 0;
  const top = Math.max(0, target.getBoundingClientRect().top + window.scrollY - headerHeight - 16);
  const requestedBehavior = behavior === "smooth" ? "smooth" : "auto";
  const previousScrollBehavior = document.documentElement.style.scrollBehavior;
  if (requestedBehavior === "auto") document.documentElement.style.scrollBehavior = "auto";
  window.scrollTo({ top, behavior: requestedBehavior });
  if (requestedBehavior === "auto") {
    requestAnimationFrame(() => {
      document.documentElement.style.scrollBehavior = previousScrollBehavior;
    });
  }
  return true;
}

function syncHomeNavigationWithScroll() {
  const page = location.pathname.split("/").pop() || "index.html";
  if (page !== "index.html") return;

  const header = document.querySelector(".site-header");
  const threshold = (header ? header.getBoundingClientRect().height : 0) + 48;
  let activeHash = "";
  ["que-es-kairos", "casos-de-uso", "beneficios"].forEach((id) => {
    const section = document.getElementById(id);
    if (section && section.getBoundingClientRect().top <= threshold) activeHash = `#${id}`;
  });
  markActiveNavigation(activeHash);
}

function initHashNavigation() {
  const root = document.documentElement;
  if (root.dataset.hashNavigationReady !== "true") {
    root.dataset.hashNavigationReady = "true";

    document.addEventListener("click", (event) => {
      const link = event.target.closest('a[href*="#"]');
      if (!link) return;

      const destination = new URL(link.href, location.href);
      const samePage = destination.origin === location.origin
        && normalizePagePath(destination.pathname) === normalizePagePath(location.pathname);
      if (!samePage || !destination.hash || !scrollToHash(destination.hash)) return;

      event.preventDefault();
      const nextUrl = `${location.pathname}${location.search}${destination.hash}`;
      history.pushState(null, "", nextUrl);
      markActiveNavigation(destination.hash);
    });

    window.addEventListener("popstate", () => {
      if (location.hash) scrollToHash(location.hash, "auto");
      else window.scrollTo({ top: 0, behavior: "auto" });
      markActiveNavigation(location.hash);
    });

    let ticking = false;
    window.addEventListener("scroll", () => {
      if (ticking) return;
      ticking = true;
      requestAnimationFrame(() => {
        syncHomeNavigationWithScroll();
        ticking = false;
      });
    }, { passive: true });
  }

  if (location.hash) {
    const initialHash = location.hash;
    const realign = () => {
      if (location.hash === initialHash) scrollToHash(initialHash, "auto");
    };
    realign();
    requestAnimationFrame(realign);
    window.setTimeout(realign, 250);
    window.setTimeout(realign, 800);
    window.addEventListener("load", realign, { once: true });
    document.querySelectorAll("main img, main video").forEach((media) => {
      const eventName = media.tagName === "VIDEO" ? "loadedmetadata" : "load";
      const isPending = media.tagName === "VIDEO" ? media.readyState < 1 : !media.complete;
      if (isPending) media.addEventListener(eventName, realign, { once: true });
    });
  }
}

function markActiveNavigation(activeHash = location.hash) {
  const currentUrl = new URL(location.href);
  document.querySelectorAll(".nav-links a").forEach((link) => {
    const href = link.getAttribute("href") || "";
    const destination = new URL(href, currentUrl);
    const samePage = destination.origin === currentUrl.origin
      && normalizePagePath(destination.pathname) === normalizePagePath(currentUrl.pathname);
    const isActive = samePage && (destination.hash
      ? destination.hash === activeHash
      : !activeHash);
    link.classList.toggle("active", isActive);
    if (isActive) link.setAttribute("aria-current", destination.hash ? "location" : "page");
    else link.removeAttribute("aria-current");
  });
}

