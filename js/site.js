function renderLegalPage() {
  const translations = window.KAIROS_LEGAL_TRANSLATIONS;
  if (!translations) return;

  const page = location.pathname.split("/").pop() || "index.html";
  const translation = translations[page];
  if (!translation) return;

  const main = document.querySelector("main");
  if (!main) return;

  if (!main.__kairosSpanishHtml) {
    main.__kairosSpanishHtml = main.innerHTML;
    main.__kairosSpanishTitle = document.title;
    main.__kairosSpanishDescription = document.querySelector('meta[name="description"]')?.content || "";
  }

  const targetLanguage = currentLanguage === "en" ? "en" : "es";
  if (main.dataset.renderedLanguage !== targetLanguage) {
    main.innerHTML = targetLanguage === "en" ? translation.html : main.__kairosSpanishHtml;
    main.dataset.renderedLanguage = targetLanguage;
  }

  document.title = targetLanguage === "en" ? translation.title : main.__kairosSpanishTitle;
  const description = document.querySelector('meta[name="description"]');
  if (description) {
    description.content = targetLanguage === "en" ? translation.description : main.__kairosSpanishDescription;
  }
}

