async function detectLanguageByIp() {
  if (location.protocol === "file:") return "";
  try {
    const response = await fetch("https://ipapi.co/json/", { cache: "no-store" });
    if (!response.ok) return "";
    const data = await response.json();
    return String(data.country_code || data.country || "").toUpperCase() === "ES" ? "es" : "en";
  } catch (error) {
    return "";
  }
}

async function resolveInitialLanguage() {
  const urlLanguage = normalizeLanguage(new URLSearchParams(location.search).get("lang"));
  if (urlLanguage) {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, urlLanguage);
    return urlLanguage;
  }

  const storedLanguage = normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));
  if (storedLanguage) return storedLanguage;

  const ipLanguage = await detectLanguageByIp();
  if (ipLanguage) return ipLanguage;

  return navigator.language && navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

async function setLanguage(language, persist = false) {
  const nextLanguage = normalizeLanguage(language) || "es";
  if (persist) localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
  if (currentLanguage === nextLanguage && lastLoadedTextFile === currentTextFile()) {
    initLanguageSwitcher();
    return;
  }

  currentLanguage = nextLanguage;
  setDocumentLanguage();
  lastLoadedText = "";
  lastLoadedTextFile = "";
  await loadTextsFromTxt();
}

async function loadTextsFromTxt() {
  try {
    const textFile = currentTextFile();
    const response = await fetch(`${rootPath()}/${textFile}?ts=${Date.now()}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`No se pudo leer ${textFile} (${response.status})`);
    const raw = new TextDecoder("utf-8").decode(await response.arrayBuffer());
    if (raw === lastLoadedText && textFile === lastLoadedTextFile) return false;
    const parsed = parseTextFile(raw);
    siteTexts = mergeDeep(DEFAULT_TEXTS, parsed);
    if (currentLanguage === "es") siteTexts.about = DEFAULT_ABOUT;
    lastLoadedText = raw;
    lastLoadedTextFile = textFile;
    renderAll();
    return true;
  } catch (error) {
    if (location.protocol === "file:" && !hasWarnedAboutLocalFile) {
      hasWarnedAboutLocalFile = true;
      console.info("Para ver cambios automáticos desde textos.txt, abre la web con abrir_web.bat.");
    } else if (location.protocol !== "file:") {
      console.warn(error);
    }
    return false;
  }
}

async function boot() {
  if ("scrollRestoration" in window.history) window.history.scrollRestoration = "manual";
  currentLanguage = await resolveInitialLanguage();
  setDocumentLanguage();
  await loadTextsFromTxt();
  if (!lastLoadedText) renderAll();
  textReloadTimer = setInterval(loadTextsFromTxt, 1500);
}

boot();
